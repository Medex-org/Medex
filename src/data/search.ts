/**
 * Centralized search index for the site-wide Command Palette.
 *
 * Built once at module load from the existing `src/data` sources (plus a
 * small curated section for programs/events/tracks that live inline in page
 * files - intentionally NOT imported from pages so the always-loaded navbar
 * bundle stays small). No runtime crawling happens anywhere.
 */

export interface SearchEntry {
  id: string;
  group: string;
  title: string;
  description: string;
  /** Internal wouter route (may include a #hash section) - or an external URL when `external` is true. */
  href: string;
  icon: LucideIcon;
  /** Extra hidden search terms so e.g. "usmle" or "systematic review" hit the right entry. */
  keywords: string[];
  /** Shown in the empty-state "quick navigation" view. */
  quick: boolean;
  /** External links open in a new tab instead of navigating with wouter. */
  external?: boolean;
}

