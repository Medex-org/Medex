const DEPARTMENT_PATHS = new Set(DEPARTMENTS.map((d) => d.href));

const PAGE_LABELS: Record<string, { title: string; icon: LucideIcon }> = {
  home: { title: "Home", icon: Home },
  about: { title: "About", icon: Info },
  team: { title: "Team & Leadership", icon: Users },
  events: { title: "Events & Opportunities", icon: CalendarDays },
  cityReps: { title: "City Reps & Campus Ambassadors", icon: MapPin },
  join: { title: "Join MEDX", icon: UserPlus },
};

// ── Pages (top-level routes; department routes live under "Departments") ──
const pageEntries: SearchEntry[] = SEO_ROUTES.filter(
  (route) => route.path && !DEPARTMENT_PATHS.has(route.path) && route.key !== "notFound",
).map((route) => {
  const label = PAGE_LABELS[route.key] ?? { title: route.title, icon: FileText };
  return {
    id: `page-${route.key}`,
    group: "Pages",
    title: label.title,
    description: route.description,
    href: route.path as string,
    icon: label.icon,
    keywords: [route.key, "page"],
    quick: true,
  };
});

